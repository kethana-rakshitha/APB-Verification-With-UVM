module tb_top;

    // =========================================================
    // CLOCK
    // =========================================================

    logic clk;


    // =========================================================
    // APB INTERFACE
    // =========================================================

    apb_if vif();


    // =========================================================
    // CLOCK CONNECTION
    // =========================================================

    assign vif.PCLK = clk;


    // =========================================================
    // DUT
    // =========================================================

    apb_slave dut (

        .PCLK    (vif.PCLK),
        .PRESETn (vif.PRESETn),

        .PSEL    (vif.PSEL),
        .PENABLE (vif.PENABLE),
        .PWRITE  (vif.PWRITE),

        .PADDR   (vif.PADDR),
        .PWDATA  (vif.PWDATA),
        .PRDATA  (vif.PRDATA),

        .PREADY  (vif.PREADY),
        .PSLVERR (vif.PSLVERR)

    );


    // =========================================================
    // CLOCK GENERATION
    // =========================================================

    initial begin

        clk = 1'b0;

        forever #5 clk = ~clk;

    end


    // =========================================================
    // RESET
    // =========================================================

    initial begin

        vif.PRESETn = 1'b0;


        repeat (3)
            @(posedge clk);


        vif.PRESETn = 1'b1;

    end


    // =========================================================
    // UVM CONFIGURATION
    // =========================================================

    initial begin

        uvm_config_db#(virtual apb_if)::set(
            null,
            "*",
            "vif",
            vif
        );

    end


    // =========================================================
    // START UVM
    // =========================================================

    initial begin

        run_test("apb_test");

    end

endmodule
